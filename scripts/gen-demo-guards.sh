#!/usr/bin/env bash
# Put stand-in guardrails with names of your choosing on a demo route, so the dashboard and the chain view
# show the names you will have in production before the real plugins are wired in.
#
#   scripts/gen-demo-guards.sh FIRST[:priority] SECOND[:priority] [...]      (default priorities 780, 775)
#   scripts/gen-demo-guards.sh --remove
#
# For each name it writes kong/plugins/<name>/, a copy of the synthetic fixture-input-guard: it reacts to
# markers in the prompt and has NOTHING to do with any real product of that name. Whatever the dashboard
# then shows for that name is scripted behaviour of the stand-in, not a measurement of a product.
#
# It also generates the probes between them, writes kong/declarative/kong.demo.fragment.yml with the route
# /ai/named (FIRST -> SECOND -> ... -> ai-proxy -> mock model), and records the plugin names in .env
# (EXTRA_KONG_PLUGINS). Then run `make up DESTINATION=grafana` (or scripts/setup.sh) to rebuild and reload Kong,
# and `scripts/mock-flow.py --path /ai/named` for traffic.
#
# Scripted behaviour, so the panels have something to show:
#   FIRST   blocks [[VIOLATION]] and, on purpose, the benign [[DECOY]] (overcatching)
#   SECOND  blocks [[VIOLATION]] and the obfuscated [[VI0LATION]] the first one misses; on [[FIXTURE_SLOW]] it
#           waits 400 ms and lets the request through without a decision (fail-open)
#   others  block [[VIOLATION]] only
# The generated plugin folders and the fragment are local: they are listed in .git/info/exclude, not committed.
set -euo pipefail
cd "$(dirname "$0")/.."
FRAG="kong/declarative/kong.demo.fragment.yml"
setenv() { touch .env; if grep -qE "^$1=" .env; then sed -i "s|^$1=.*|$1=$2|" .env; else echo "$1=$2" >> .env; fi; }
exclude() { [[ -d .git ]] && { grep -qxF "$1" .git/info/exclude 2>/dev/null || echo "$1" >> .git/info/exclude; }; true; }

if [[ "${1:-}" == "--remove" ]]; then
  for d in kong/plugins/*/; do [[ -f "$d/.demo-guard" ]] && rm -rf "$d" && echo "removed $d"; done
  rm -f "$FRAG"; setenv EXTRA_KONG_PLUGINS ""
  echo "removed. Run scripts/setup.sh --destination grafana to reload Kong without them."; exit 0
fi
[[ $# -ge 1 && "$1" != -* ]] || { sed -n '2,22p' "$0"; exit 2; }

NAMES=(); PRIOS=(); next=780
for a in "$@"; do
  n="${a%%:*}"; p="${a#*:}"; [[ "$p" == "$a" ]] && p=$next
  [[ "$n" =~ ^[a-z][a-z0-9-]{1,40}$ ]] || { echo "name '$n': lowercase letters, digits and - only" >&2; exit 2; }
  [[ "$p" =~ ^[0-9]+$ ]] && (( p > 771 && p < 790 )) || { echo "priority for $n must be between 772 and 789 (below the head plugin, above ai-proxy)" >&2; exit 2; }
  [[ -d "kong/plugins/$n" && ! -f "kong/plugins/$n/.demo-guard" ]] && { echo "kong/plugins/$n exists and is not a demo guard" >&2; exit 2; }
  NAMES+=("$n"); PRIOS+=("$p"); next=$(( p - 5 ))
done

for d in kong/plugins/*/; do [[ -f "$d/.demo-guard" ]] && rm -rf "$d"; done
SPEC=""
for i in "${!NAMES[@]}"; do
  n="${NAMES[$i]}"; p="${PRIOS[$i]}"; d="kong/plugins/$n"; mkdir -p "$d"
  for f in handler.lua schema.lua; do
    sed -e "s/fixture-input-guard/$n/g" -e "s/PRIORITY = 775/PRIORITY = $p/" \
        -e "s/request blocked by policy (fixture)/request blocked by policy ($n stand-in)/" kong/plugins/fixture-input-guard/$f > "$d/$f"
  done
  sed -i "1i -- GENERATED by scripts/gen-demo-guards.sh: a synthetic stand-in named \"$n\". Not the real product of that name." "$d/handler.lua"
  : > "$d/.demo-guard"; exclude "$d/"; SPEC+="$n:$p,"
done
SPEC+="ai-proxy:770"

OUT="$(scripts/gen-probes.sh --guardrails "$SPEC")"
PROBES="$(sed -n 's/^probes written: //p' <<<"$OUT")"
for p in $PROBES; do exclude "kong/plugins/gro-probe-$p/"; done
exclude "$FRAG"

guard_cfg() {  # $1 = index
  case "$1" in
    0) echo '{ mode: block, deny_markers: [ "[[VIOLATION]]" ], decoy_markers: [ "[[DECOY]]" ], slow_markers: [] }';;
    1) echo '{ mode: block, deny_markers: [ "[[VIOLATION]]", "[[VI0LATION]]" ], decoy_markers: [], slow_markers: [ "[[FIXTURE_SLOW]]" ], slow_ms: 400 }';;
    *) echo '{ mode: block, deny_markers: [ "[[VIOLATION]]" ], decoy_markers: [], slow_markers: [] }';;
  esac
}
LIST="$(printf '%s, ' "${NAMES[@]}")"; LIST="${LIST%, }"
TIMEOUTS=""; [[ ${#NAMES[@]} -ge 2 ]] && TIMEOUTS="
              guardrail_timeouts: { ${NAMES[1]}: 400 }"
{
  cat <<YAML
# GENERATED by scripts/gen-demo-guards.sh. Stand-in guardrails named: $LIST. Synthetic, not the real products.
  - name: mock-llm-named
    url: http://mock-llm:8080
    routes:
      - name: ai-named-route
        paths: [ /ai/named ]
        strip_path: true
        plugins:
          - name: key-auth
            config: { key_names: [ apikey ], hide_credentials: true }
          - name: guardrail-observer
            config:
              environment: local
              policy_version: "named-v1"
              runner_shared_secret: "{vault://env/go-runner-secret}"
              capture_body_mode: bounded        # synthetic traffic only
              max_capture_bytes: 1024
              guardrail_plugins: [ $LIST ]$TIMEOUTS
          - name: guardrail-observer-tail
            config: { capture_body_mode: hash }
YAML
  for p in $PROBES; do echo "          - name: gro-probe-$p"; done
  for i in "${!NAMES[@]}"; do printf '          - name: %s\n            config: %s\n' "${NAMES[$i]}" "$(guard_cfg "$i")"; done
  cat <<'YAML'
          - name: ai-proxy
            config:
              route_type: llm/v1/chat
              auth: { header_name: Authorization, header_value: "Bearer mock-key" }
              logging: { log_statistics: true, log_payloads: false }
              model:
                provider: openai
                name: mock-gpt
                options: { upstream_url: http://mock-llm:8080/v1/chat/completions }
          - name: http-log
            config:
              http_endpoint: "{vault://env/go-ingest-endpoint}"
              timeout: 5000
              queue: { max_batch_size: 50, max_coalescing_delay: 1, max_entries: 10000, max_retry_time: 120 }

YAML
} > "$FRAG"

EXTRA=""; for n in "${NAMES[@]}"; do EXTRA+=",$n"; done; for p in $PROBES; do case "$p" in 773|765|750) ;; *) EXTRA+=",gro-probe-$p";; esac; done   # those three are always loaded
setenv EXTRA_KONG_PLUGINS "$EXTRA"
echo "stand-in guardrails: $LIST   probes: $PROBES   route: /ai/named"
echo "next: scripts/setup.sh --destination grafana   then   scripts/mock-flow.py --path /ai/named"
